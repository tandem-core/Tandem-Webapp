"""Regenerate prescription dosing clips with ffmpeg (run from the repo root)."""
import json
import subprocess
from pathlib import Path

# Include enough surrounding speech to preserve the meaning of each dose.
clips = [
    ('01_medication_shared_decision', 'med-1', 313.3, 328.1),
    ('02_methotrexate_full_consultation', 'med-1', 312.2, 324.9),
    ('02_methotrexate_full_consultation', 'med-3', 435.2, 455.9),
    ('03_prescription_refill_counseling', 'med-1', 10.2, 15.7),
]
output = Path('public/demo-audio/excerpts')
output.mkdir(parents=True, exist_ok=True)
manifest = {}
for source, medicine, start, end in clips:
    filename = f'{source}-{medicine}-dose.mp3'
    subprocess.run([
        'ffmpeg', '-hide_banner', '-loglevel', 'error', '-y',
        '-i', f'public/demo-audio/clip_{source}.mp3',
        '-ss', str(start), '-t', str(end - start), '-map', '0:a:0',
        '-c:a', 'libmp3lame', '-b:a', '96k', str(output / filename),
    ], check=True)
    duration = float(subprocess.check_output([
        'ffprobe', '-v', 'error', '-show_entries', 'format=duration',
        '-of', 'default=noprint_wrappers=1:nokey=1', str(output / filename),
    ], text=True))
    assert abs(duration - (end - start)) < 0.2
    manifest[f'clip:{source}/{medicine}'] = {'audioUrl': f'/demo-audio/excerpts/{filename}', 'durationSec': round(duration)}
    print(f'{filename}: {duration:.2f}s')
Path('lib/dose-excerpts.ts').write_text(
    '// Generated by scripts/generate-dose-excerpts.py.\n'
    'export const doseExcerpts: Record<string, { audioUrl: string; durationSec: number }> = '
    + json.dumps(manifest, indent=2) + ';\n'
)
